package com.sierra.omniagent.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.sierra.omniagent.data.model.MediaType
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun MediaGeneratorScreen(
    initialMediaType: MediaType = MediaType.IMAGE,
    modifier: Modifier = Modifier
) {
    var mediaType by remember { mutableStateOf(initialMediaType) }
    var prompt by remember { mutableStateOf("") }
    var selectedAspectRatio by remember { mutableStateOf("16:9") }
    var selectedResolution by remember { mutableStateOf("1080p") }
    var selectedStyle by remember { mutableStateOf("Photorealistic") }
    var isGenerating by remember { mutableStateOf(false) }
    var progress by remember { mutableStateOf(0f) }
    var resultGenerated by remember { mutableStateOf(false) }

    val coroutineScope = rememberCoroutineScope()
    val scrollState = rememberScrollState()

    val aspectRatios = listOf("1:1", "16:9", "9:16", "4:3", "3:4")
    val styles = listOf("Raw Prompt", "Photorealistic", "Artistic", "Cinematic")
    val resolutions = listOf("720p", "1080p", "4k")

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Text(
                            if (mediaType == MediaType.IMAGE) "Image Generation" else "Video Generation",
                            fontWeight = FontWeight.Bold,
                            fontSize = 18.sp
                        )
                        Text(
                            if (mediaType == MediaType.IMAGE) "Gemini Pro Image / Imagen" else "Veo 3.1 Next-Gen Video",
                            fontSize = 11.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surface
                )
            )
        },
        modifier = modifier
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .background(MaterialTheme.colorScheme.background)
                .verticalScroll(scrollState)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            // Media Type Tabs
            TabRow(
                selectedTabIndex = if (mediaType == MediaType.IMAGE) 0 else 1,
                containerColor = MaterialTheme.colorScheme.surfaceVariant,
                modifier = Modifier
                    .clip(RoundedCornerShape(12.dp))
                    .testTag("media_type_tabs")
            ) {
                Tab(
                    selected = mediaType == MediaType.IMAGE,
                    onClick = { mediaType = MediaType.IMAGE },
                    text = { Text("Image Studio") }
                )
                Tab(
                    selected = mediaType == MediaType.VIDEO,
                    onClick = { mediaType = MediaType.VIDEO },
                    text = { Text("Veo Video") }
                )
            }

            // Prompt Input Card
            Card(
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text(
                        "Prompt",
                        fontWeight = FontWeight.Bold,
                        fontSize = 14.sp,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Spacer(Modifier.height(8.dp))
                    OutlinedTextField(
                        value = prompt,
                        onValueChange = { prompt = it },
                        placeholder = {
                            Text(
                                if (mediaType == MediaType.IMAGE) "Describe an image in rich sensory detail..."
                                else "Describe a dynamic video scene with camera movement..."
                            )
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("media_prompt_input"),
                        minLines = 3,
                        maxLines = 6
                    )
                }
            }

            // Aspect Ratio Selector
            Text("Aspect Ratio", fontWeight = FontWeight.SemiBold, fontSize = 14.sp)
            Row(
                horizontalArrangement = Arrangement.spacedBy(8.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                aspectRatios.forEach { ratio ->
                    FilterChip(
                        selected = selectedAspectRatio == ratio,
                        onClick = { selectedAspectRatio = ratio },
                        label = { Text(ratio) },
                        modifier = Modifier.testTag("chip_ratio_$ratio")
                    )
                }
            }

            // Style Selector (for Images)
            if (mediaType == MediaType.IMAGE) {
                Text("Visual Style", fontWeight = FontWeight.SemiBold, fontSize = 14.sp)
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    styles.forEach { style ->
                        FilterChip(
                            selected = selectedStyle == style,
                            onClick = { selectedStyle = style },
                            label = { Text(style) },
                            modifier = Modifier.testTag("chip_style_$style")
                        )
                    }
                }
            } else {
                // Resolution Selector (for Videos)
                Text("Video Resolution", fontWeight = FontWeight.SemiBold, fontSize = 14.sp)
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    resolutions.forEach { res ->
                        FilterChip(
                            selected = selectedResolution == res,
                            onClick = { selectedResolution = res },
                            label = { Text(res) },
                            modifier = Modifier.testTag("chip_res_$res")
                        )
                    }
                }
            }

            // Generate Button
            Button(
                onClick = {
                    if (prompt.isNotBlank() && !isGenerating) {
                        isGenerating = true
                        progress = 0.1f
                        resultGenerated = false
                        coroutineScope.launch {
                            for (i in 1..9) {
                                delay(600)
                                progress = i * 0.1f
                            }
                            isGenerating = false
                            resultGenerated = true
                        }
                    }
                },
                enabled = prompt.isNotBlank() && !isGenerating,
                modifier = Modifier
                    .fillMaxWidth()
                    .height(52.dp)
                    .testTag("generate_media_button"),
                shape = RoundedCornerShape(12.dp)
            ) {
                if (isGenerating) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(24.dp),
                        color = Color.White,
                        strokeWidth = 2.dp
                    )
                    Spacer(Modifier.width(12.dp))
                    Text(
                        if (mediaType == MediaType.IMAGE) "Rendering Image (${(progress * 100).toInt()}%)..."
                        else "Synthesizing Veo Video (${(progress * 100).toInt()}%)..."
                    )
                } else {
                    Icon(
                        if (mediaType == MediaType.IMAGE) Icons.Default.Create else Icons.Default.PlayArrow,
                        contentDescription = null
                    )
                    Spacer(Modifier.width(8.dp))
                    Text(
                        if (mediaType == MediaType.IMAGE) "Generate High-Res Image"
                        else "Synthesize Veo Video"
                    )
                }
            }

            // Result Preview Card
            if (resultGenerated) {
                Card(
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("media_result_card")
                ) {
                    Column(
                        modifier = Modifier.padding(16.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .height(220.dp)
                                .clip(RoundedCornerShape(8.dp))
                                .background(MaterialTheme.colorScheme.surface),
                            contentAlignment = Alignment.Center
                        ) {
                            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                                Icon(
                                    if (mediaType == MediaType.IMAGE) Icons.Default.Face else Icons.Default.PlayArrow,
                                    contentDescription = null,
                                    modifier = Modifier.size(48.dp),
                                    tint = MaterialTheme.colorScheme.primary
                                )
                                Spacer(Modifier.height(8.dp))
                                Text(
                                    "Generated: \"$prompt\"",
                                    fontSize = 12.sp,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant
                                )
                            }
                        }

                        Spacer(Modifier.height(12.dp))

                        Row(
                            horizontalArrangement = Arrangement.spacedBy(8.dp),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            OutlinedButton(
                                onClick = { /* Save/Download */ },
                                modifier = Modifier.weight(1f)
                            ) {
                                Icon(Icons.Default.Share, contentDescription = null, modifier = Modifier.size(16.dp))
                                Spacer(Modifier.width(4.dp))
                                Text("Share")
                            }
                            Button(
                                onClick = { /* Export */ },
                                modifier = Modifier.weight(1f)
                            ) {
                                Icon(Icons.Default.Check, contentDescription = null, modifier = Modifier.size(16.dp))
                                Spacer(Modifier.width(4.dp))
                                Text("Save Asset")
                            }
                        }
                    }
                }
            }
        }
    }
}
